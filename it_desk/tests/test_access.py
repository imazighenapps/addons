# -*- coding: utf-8 -*-
"""Access rights, tested the way a customer meets them.

Generated by module_kit from the spec: the module group opens the door and
an ordinary internal user stays outside it.
"""
from odoo.exceptions import AccessError
from odoo.tests import TransactionCase, new_test_user, tagged


@tagged("post_install", "-at_install")
class TestAccessRights(TransactionCase):
    MODEL = 'it.asset'

    def test_01_outsider_is_refused(self):
        outsider = new_test_user(
            self.env, login="access_it_desk_out", groups="base.group_user")
        with self.assertRaises(AccessError):
            self.env[self.MODEL].with_user(outsider).search([])

    def test_02_group_member_is_allowed(self):
        member = new_test_user(
            self.env, login="access_it_desk_in",
            groups="base.group_user,it_desk.group_itdesk_user")
        try:
            self.env[self.MODEL].with_user(member).search([])
        except AccessError:
            self.fail("the it_desk user group must be able to read "
                      "%s" % self.MODEL)


@tagged("post_install", "-at_install")
class TestCompanyIsolation(TransactionCase):
    """Company A must never read the rows of company B."""
    MODELS = ['it.asset', 'it.assignment']

    def _rules(self):
        name = "ir.access" if "ir.access" in self.env.registry else "ir.rule"
        model = self.env[name]
        field = "domain" if "domain" in model._fields else "domain_force"
        return model.sudo().search([("model_id.model", "in", self.MODELS)]), field

    def test_03_every_model_has_its_company_rule(self):
        rules, field = self._rules()
        protected = set()
        for rule in rules:
            if "company_ids" in (rule[field] or ""):
                protected.add(rule.model_id.model)
        missing = sorted(set(self.MODELS) - protected)
        self.assertFalse(
            missing,
            "no company rule on %s: those rows would be shared between companies"
            % ", ".join(missing))
